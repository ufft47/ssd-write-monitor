<#
    setup-task.ps1 —— 建立 / 更新 Windows 排程工作。

    設計重點：使用 S4U（不儲存密碼、不需管理員）讓工作在背景工作階段執行，
    這樣每隔幾分鐘執行一次也不會閃出主控台視窗。
    若 S4U 註冊失敗，才退回 Interactive（會在登入的工作階段執行，可能短暫閃視窗）。

    移除：Unregister-ScheduledTask -TaskName DiskMonitor -Confirm:$false
#>
[CmdletBinding()]
param(
    [string]$Root = 'D:\dev\disk-monitor',
    [int]$IntervalMinutes = 1,
    [string]$TaskName = 'DiskMonitor'
)

$ErrorActionPreference = 'Stop'

$runner = Join-Path $Root 'src\disk-monitor-run.ps1'
if (-not (Test-Path -LiteralPath $runner)) { throw "runner not found: $runner" }

$psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'

# 用 wscript 包一層，讓 PowerShell 以「完全隱藏視窗」啟動。
# 直接讓排程呼叫 powershell.exe（即使加了 -WindowStyle Hidden）仍可能每秒閃一次主控台。
$vbsPath = Join-Path $Root 'src\run-hidden.vbs'
$vbs = @'
' Auto-generated by setup-task.ps1 - do not edit manually.
Set sh = CreateObject("WScript.Shell")
sh.Run """{PS}"" -NoProfile -NonInteractive -ExecutionPolicy Bypass -File ""{RUNNER}""", 0, False
'@ -replace '\{PS\}', $psExe -replace '\{RUNNER\}', $runner
[IO.File]::WriteAllText($vbsPath, $vbs, (New-Object System.Text.UTF8Encoding($false)))

$wscript = Join-Path $env:SystemRoot 'System32\wscript.exe'
$action = New-ScheduledTaskAction -Execute $wscript -Argument ('//nologo "{0}"' -f $vbsPath)

$trigger = New-ScheduledTaskTrigger -Once -At ((Get-Date).AddMinutes(2)) `
    -RepetitionInterval (New-TimeSpan -Minutes $IntervalMinutes) `
    -RepetitionDuration ([TimeSpan]::FromDays(3650))

$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Minutes 10)

$userId = '{0}\{1}' -f $env:USERDOMAIN, $env:USERNAME

$registered = $false
foreach ($logonType in @('S4U', 'Interactive')) {
    try {
        $principal = New-ScheduledTaskPrincipal -UserId $userId -LogonType $logonType -RunLevel Limited
        Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
            -Principal $principal -Description '長期磁碟 IO 監控：每分鐘取樣，每小時產出報告。' -Force -ErrorAction Stop | Out-Null
        $check = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
        if ($null -ne $check) {
            Write-Output ("registered ({0}): {1}" -f $logonType, $check.State)
            if ($logonType -ne 'S4U') { Write-Output 'WARNING: 退回 Interactive 模式，每分鐘可能短暫閃出主控台視窗。' }
            $registered = $true
            break
        }
        Write-Output ("registration returned without error but task not found ({0})" -f $logonType)
    } catch {
        Write-Output ("registration failed ({0}): {1}" -f $logonType, $_.Exception.Message)
    }
}
if (-not $registered) { throw 'could not register the scheduled task' }

Get-ScheduledTask -TaskName $TaskName | Select-Object TaskName, State | Format-List
Get-ScheduledTaskInfo -TaskName $TaskName | Select-Object LastRunTime, LastTaskResult, NextRunTime | Format-List
