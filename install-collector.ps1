<#
    install-collector.ps1 —— 安裝「精確歸因 collector」（必須以系統管理員身分執行）

    做的事：
      1. 確認目前是提權工作階段（否則直接中止，不做任何變更）
      2. 跑 cwatch.exe selftest：寫 64 MB 到 C:\Users\...\Temp 並確認歸因表抓到
      3. 註冊排程工作 CWatchCollector（登入時啟動、最高權限、無執行時間上限、失敗自動重啟）
      4. 立即啟動並驗證心跳與歸因檔成長
      5. 結果寫到 logs\install-collector-<時間>.txt

    還原：
      Unregister-ScheduledTask -TaskName CWatchCollector -Confirm:$false
      Remove-Item 'D:\dev\disk-monitor\data\state\collector.json'
#>
[CmdletBinding()]
param(
    [string]$Root = 'D:\dev\disk-monitor',
    [string]$TaskName = 'CWatchCollector',
    [switch]$SkipSelfTest
)

$ErrorActionPreference = 'Stop'
$logDir = Join-Path $Root 'logs'
if (-not (Test-Path -LiteralPath $logDir)) { New-Item -ItemType Directory -Path $logDir -Force | Out-Null }
$logPath = Join-Path $logDir ('install-collector-' + (Get-Date -Format 'yyyyMMdd-HHmmss') + '.txt')
$lines = New-Object System.Collections.Generic.List[string]
function Say([string]$s) { Write-Host $s; $lines.Add($s) }

Say ('=== CWatch collector install ===  ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
Say ('root : ' + $Root)

# ---------- 1. 提權檢查 ----------
$id = [Security.Principal.WindowsIdentity]::GetCurrent()
$isAdmin = (New-Object Security.Principal.WindowsPrincipal($id)).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
Say ('user : ' + $id.Name)
Say ('admin: ' + $isAdmin)
if (-not $isAdmin) {
    Say ''
    Say '尚未提權。請用「以系統管理員身分執行」的 PowerShell 重跑這支腳本：'
    Say ('  Start-Process powershell -Verb RunAs -ArgumentList ''-NoExit'',''-ExecutionPolicy'',''Bypass'',''-File'',''{0}'' ' -f $PSCommandPath)
    [IO.File]::WriteAllText($logPath, ($lines -join "`r`n"), (New-Object Text.UTF8Encoding($false)))
    exit 2
}

$exe = Join-Path $Root 'src\cwatch\cwatch.exe'
if (-not (Test-Path -LiteralPath $exe)) { Say ('找不到 ' + $exe); exit 3 }

# ---------- 2. selftest ----------
if (-not $SkipSelfTest) {
    Say ''
    Say '--- selftest（寫 64 MB 到 C: 的 Temp 並確認歸因）---'
    $out = & $exe selftest $Root 2>&1
    foreach ($l in $out) { Say ('  ' + $l) }
    $code = $LASTEXITCODE
    Say ('  selftest exit = ' + $code)
    if ($code -ne 0) {
        Say ''
        Say '[中止] selftest 未通過，不註冊排程。'
        Say '        BYTES_MISSING → ETW 抓不到位元組，需要改用備援模式（回報此結果即可）。'
        [IO.File]::WriteAllText($logPath, ($lines -join "`r`n"), (New-Object Text.UTF8Encoding($false)))
        exit 4
    }
}

# ---------- 3. 註冊排程 ----------
Say ''
Say '--- 註冊排程工作 ---'
$action = New-ScheduledTaskAction -Execute $exe -Argument ('collect "{0}"' -f $Root) -WorkingDirectory (Join-Path $Root 'src\cwatch')
if ($true) {
    # 主控台程式若直接被排程啟動，桌面會出現黑視窗；關掉它 = 送出 CTRL_CLOSE_EVENT，
    # 程式以 0xC000013A 結束（實際發生過）。改用 wscript 隱藏啟動。
    $vbsPath2 = Join-Path $Root 'src\cwatch\collector-hidden.vbs'
    $vbs2 = @'
' Auto-generated by install-collector.ps1 - do not edit
Set sh = CreateObject("WScript.Shell")
sh.Run """{EXE}"" collect ""{ROOT}""", 0, False
'@ -replace '\{EXE\}', $exe -replace '\{ROOT\}', $Root
    [IO.File]::WriteAllText($vbsPath2, $vbs2, (New-Object System.Text.UTF8Encoding($false)))
    $action = New-ScheduledTaskAction -Execute (Join-Path $env:SystemRoot 'System32\wscript.exe') -Argument ('//nologo "{0}"' -f $vbsPath2) -WorkingDirectory (Join-Path $Root 'src\cwatch')
}
$trigger = New-ScheduledTaskTrigger -AtLogOn -User ('{0}\{1}' -f $env:USERDOMAIN, $env:USERNAME)
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero) `
    -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)
$principal = New-ScheduledTaskPrincipal -UserId ('{0}\{1}' -f $env:USERDOMAIN, $env:USERNAME) -LogonType Interactive -RunLevel Highest

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
    -Principal $principal -Description 'CWatch: ETW 逐進程/逐磁碟區寫入歸因（需要管理員）' -Force | Out-Null
Say ('  已註冊 ' + $TaskName + '（LogonType=Interactive, RunLevel=Highest）')

# ---------- 4. 啟動 + 驗證 ----------
Say ''
Say '--- 啟動並驗證 ---'
Start-ScheduledTask -TaskName $TaskName
$hb = Join-Path $Root 'data\state\collector.json'
$deadline = (Get-Date).AddSeconds(45)
$ok = $false
while ((Get-Date) -lt $deadline) {
    Start-Sleep -Seconds 3
    if (Test-Path -LiteralPath $hb) {
        try {
            $j = Get-Content -LiteralPath $hb -Raw -Encoding UTF8 | ConvertFrom-Json
            if ($j.state -eq 'running' -and $j.bytes_seen -gt 0) { $ok = $true; break }
        } catch { }
    }
}
if ($ok) {
    Say ('  心跳 OK：state=running, bytes_seen={0:N0}' -f [double]$j.bytes_seen)
} else {
    Say '  [警告] 45 秒內沒有看到有效心跳，請檢查 logs\collector.log'
    Say ('  collector.log 最後幾行：')
    $cl = Join-Path $Root 'logs\collector.log'
    if (Test-Path -LiteralPath $cl) { (Get-Content -LiteralPath $cl -Encoding UTF8 -Tail 6) | ForEach-Object { Say ('    ' + $_) } }
}

Say ''
Say '--- 排程狀態 ---'
Get-ScheduledTaskInfo -TaskName $TaskName | Select-Object LastRunTime, LastTaskResult, NextRunTime |
    Format-List | Out-String | ForEach-Object { Say $_ }

Say ''
Say ('done. 紀錄：' + $logPath)
[IO.File]::WriteAllText($logPath, ($lines -join "`r`n"), (New-Object Text.UTF8Encoding($false)))
if (-not $ok) { exit 5 }
exit 0
