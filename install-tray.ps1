<#
    install-tray.ps1 —— 安裝托盤常駐（一般權限即可，不需管理員）

    註冊排程工作 CWatchTray：登入時啟動，透過 wscript 隱藏視窗。
    托盤會自行確保儀表板（localhost:8737）有在跑。

    還原：
      Unregister-ScheduledTask -TaskName CWatchTray -Confirm:$false
#>
[CmdletBinding()]
param(
    [string]$Root = 'D:\dev\disk-monitor',
    [int]$Port = 8737,
    [string]$TaskName = 'CWatchTray'
)

$ErrorActionPreference = 'Stop'

$scriptPath = Join-Path $Root 'src\tray\cwatch-tray.ps1'
if (-not (Test-Path -LiteralPath $scriptPath)) { throw "找不到 $scriptPath" }

$psExe = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$vbsPath = Join-Path $Root 'src\tray\tray-hidden.vbs'
$vbs = @'
' Auto-generated by install-tray.ps1 - do not edit manually.
Set sh = CreateObject("WScript.Shell")
sh.Run """{PS}"" -STA -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File ""{SCRIPT}"" -Root ""{ROOT}"" -Port {PORT}", 0, False
'@ -replace '\{PS\}', $psExe -replace '\{SCRIPT\}', $scriptPath -replace '\{ROOT\}', $Root -replace '\{PORT\}', $Port
[IO.File]::WriteAllText($vbsPath, $vbs, (New-Object System.Text.UTF8Encoding($false)))

$wscript = Join-Path $env:SystemRoot 'System32\wscript.exe'
$action = New-ScheduledTaskAction -Execute $wscript -Argument ('//nologo "{0}"' -f $vbsPath)
$trigger = New-ScheduledTaskTrigger -AtLogOn -User ('{0}\{1}' -f $env:USERDOMAIN, $env:USERNAME)
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero)
$principal = New-ScheduledTaskPrincipal -UserId ('{0}\{1}' -f $env:USERDOMAIN, $env:USERNAME) -LogonType Interactive -RunLevel Limited

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $settings `
    -Principal $principal -Description 'CWatch: 系統匣 + 本機儀表板' -Force | Out-Null
Write-Output ("registered: {0}  -> {1}" -f $TaskName, $vbsPath)

Start-ScheduledTask -TaskName $TaskName
Start-Sleep -Seconds 6

$running = @(Get-CimInstance Win32_Process -Filter "Name = 'powershell.exe'" |
    Where-Object { $_.CommandLine -and $_.CommandLine.Contains('cwatch-tray.ps1') })
Write-Output ("tray process : {0} 個" -f $running.Count)

$open = $false
try {
    $c = New-Object System.Net.Sockets.TcpClient
    $iar = $c.BeginConnect('127.0.0.1', $Port, $null, $null)
    $open = $iar.AsyncWaitHandle.WaitOne(2000)
    if ($open) { $c.EndConnect($iar) }
    $c.Close()
} catch { $open = $false }
Write-Output ("dashboard    : " + $(if ($open) { ('http://localhost:{0}/ 可連線' -f $Port) } else { '連不上（請看 logs）' }))
