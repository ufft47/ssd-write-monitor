<#
    fix-collector-hidden.ps1 —— 把 collector 改成「隱藏視窗」啟動（必須以系統管理員身分執行）

    為什麼：collector 是主控台程式，排程直接啟動它會在桌面出現一個黑色視窗。
    關掉那個視窗 = 送出 CTRL_CLOSE_EVENT，程式會以 0xC000013A（STATUS_CONTROL_C_EXIT）結束。
    實際發生過一次，資料因此中斷。

    做法：改用 wscript 呼叫 collector-hidden.vbs（Run(..., 0, ...) = 完全不顯示視窗）。

    還原：把動作改回 cwatch.exe（見檔尾註解）
#>
[CmdletBinding()]
param(
    [string]$Root = 'D:\dev\disk-monitor',
    [string]$TaskName = 'CWatchCollector'
)

$ErrorActionPreference = 'Stop'
$id = [Security.Principal.WindowsIdentity]::GetCurrent()
$isAdmin = (New-Object Security.Principal.WindowsPrincipal($id)).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
"admin = $isAdmin  (user $($id.Name))"
if (-not $isAdmin) {
    "尚未提權。請用： Start-Process powershell -Verb RunAs -ArgumentList '-NoExit','-ExecutionPolicy','Bypass','-File','$PSCommandPath'"
    exit 2
}

$exe = Join-Path $Root 'src\cwatch\cwatch.exe'
if (-not (Test-Path -LiteralPath $exe)) { "找不到 $exe"; exit 3 }

# ---------- 產生隱藏啟動器 ----------
$vbsPath = Join-Path $Root 'src\cwatch\collector-hidden.vbs'
$vbs = @'
' Auto-generated by fix-collector-hidden.ps1 - 以完全隱藏視窗啟動 collector
Set sh = CreateObject("WScript.Shell")
sh.Run """{EXE}"" collect ""{ROOT}""", 0, False
'@ -replace '\{EXE\}', $exe -replace '\{ROOT\}', $Root
[IO.File]::WriteAllText($vbsPath, $vbs, (New-Object System.Text.UTF8Encoding($false)))
"  已產生 $vbsPath"

# ---------- 換動作 ----------
$wscript = Join-Path $env:SystemRoot 'System32\wscript.exe'
$action = New-ScheduledTaskAction -Execute $wscript -Argument ('//nologo "{0}"' -f $vbsPath) -WorkingDirectory (Join-Path $Root 'src\cwatch')
Set-ScheduledTask -TaskName $TaskName -Action $action | Out-Null
"  已更新 $TaskName 的動作 → wscript + collector-hidden.vbs"

# ---------- 重啟 ----------
Stop-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
Start-Sleep -Seconds 3
$procs = @(Get-Process -Name 'cwatch' -ErrorAction SilentlyContinue)
foreach ($p in $procs) {
    try { Stop-Process -Id $p.Id -Force -ErrorAction Stop; "  已結束殘留 pid=$($p.Id)" } catch { }
}
Start-Sleep -Seconds 2
$stopFile = Join-Path $Root 'data\state\collector.stop'
if (Test-Path -LiteralPath $stopFile) { Remove-Item -LiteralPath $stopFile -Force; '  已清除 collector.stop' }
Start-ScheduledTask -TaskName $TaskName

# ---------- 驗證 ----------
"--- 驗證 ---"
$deadline = (Get-Date).AddSeconds(60)
$ok = $false
while ((Get-Date) -lt $deadline) {
    Start-Sleep -Seconds 5
    $hb = Join-Path $Root 'data\state\collector.json'
    if (Test-Path -LiteralPath $hb) {
        try {
            $j = Get-Content -LiteralPath $hb -Raw -Encoding UTF8 | ConvertFrom-Json
            if ($j.state -eq 'running' -and $j.bytes_seen -gt 0) { $ok = $true; break }
        } catch { }
    }
}

$p = @(Get-Process -Name 'cwatch' -ErrorAction SilentlyContinue)
if ($p.Count -gt 0) {
    foreach ($x in $p) {
        $visible = '未知'
        try { $visible = if ($x.MainWindowHandle -eq 0) { '無視窗（正確）' } else { '有視窗（不正確）' } } catch { }
        "  pid=$($x.Id)  $visible  WS=$([int]($x.WorkingSet64/1MB)) MB"
    }
} else { '  [警告] 找不到 cwatch 程序' }

if ($ok) {
    $dev = 0.0
    if ($null -ne $j.bytes_device) { $dev = [double]$j.bytes_device }
    $pct = 0.0
    if ([double]$j.bytes_seen -gt 0) { $pct = $dev / [double]$j.bytes_seen * 100 }
    "  心跳 OK：{0}  bytes_seen={1:N2} GB  無法歸屬={2:N1}%" -f $j.updated, ([double]$j.bytes_seen/1GB), $pct
    if ($pct -gt 40) {
        "  註：無法歸屬比例高，通常是當下有大檔複製（未緩衝 I/O 或分頁 I/O 沒有檔名），不是程式壞掉。"
    }
} else {
    "  [警告] 60 秒內沒有心跳"
    $cl = Join-Path $Root 'logs\collector.log'
    if (Test-Path -LiteralPath $cl) { Get-Content -LiteralPath $cl -Encoding UTF8 -Tail 8 | ForEach-Object { '    ' + $_ } }
}
Get-ScheduledTaskInfo -TaskName $TaskName | Select-Object LastRunTime, LastTaskResult | Format-List

# 還原動作（若日後要改回）：Set-ScheduledTask -TaskName CWatchCollector `
#   -Action (New-ScheduledTaskAction -Execute "$Root\src\cwatch\cwatch.exe" -Argument "collect `"$Root`"")
if (-not $ok) { exit 6 }
exit 0
